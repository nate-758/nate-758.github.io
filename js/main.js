const languageButtons = document.querySelectorAll("[data-language]");
const translatableElements = document.querySelectorAll("[data-i18n]");

function setLanguage(language) {
  const selectedLanguage = translations[language] ? language : "en";
  document.documentElement.lang = selectedLanguage;

  translatableElements.forEach((element) => {
    const translation = translations[selectedLanguage][element.dataset.i18n];
    if (translation) {
      if (element.dataset.i18nAttribute) {
        element.setAttribute(element.dataset.i18nAttribute, translation);
      } else {
        element.textContent = translation;
      }
    }
  });

  document.querySelectorAll(".brand[aria-label]").forEach((brand) => {
    brand.setAttribute("aria-label", translations[selectedLanguage].homeLabel);
  });
  document.querySelector(".main-nav").setAttribute("aria-label", translations[selectedLanguage].mainNavigation);
  document.querySelector(".language-switch").setAttribute("aria-label", translations[selectedLanguage].chooseLanguage);

  languageButtons.forEach((button) => {
    const isSelected = button.dataset.language === selectedLanguage;
    button.classList.toggle("is-active", isSelected);
    button.setAttribute("aria-pressed", String(isSelected));
  });

  document.dispatchEvent(new CustomEvent("languagechange", {
    detail: { language: selectedLanguage }
  }));

  try {
    localStorage.setItem("chronoConnectionsLanguage", selectedLanguage);
  } catch (error) {
    console.warn("Could not save the language preference.", error);
  }
}

languageButtons.forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.language));
});

let savedLanguage = "en";
try {
  const storedLanguage = localStorage.getItem("chronoConnectionsLanguage");
  if (storedLanguage && translations[storedLanguage]) {
    savedLanguage = storedLanguage;
  }
} catch (error) {
  console.warn("Could not load the saved language preference.", error);
}
setLanguage(savedLanguage);

document.querySelector("#current-year").textContent = String(new Date().getFullYear());
